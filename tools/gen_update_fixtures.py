#!/usr/bin/env python3
"""Generate S-101 update-robustness fixtures (docs/update-robustness-contract.md rev 1.2).

Python 3 standard library only. Deterministic: fixed seed, no timestamps, no dict-order or
filesystem-order dependence, binary writes ("\\n" only). Running it twice yields identical bytes.

Base: testdata/s101/101AA00DS0003.000 (IHO TDS, DSID DSED "9.0" = ED 9 UPD 0).

    python3 tools/gen_update_fixtures.py                 # write testdata/s101/updates/
    python3 tools/gen_update_fixtures.py --out DIR       # write elsewhere (reproducibility check)
    python3 tools/gen_update_fixtures.py --write-manifest  # also refresh fixtures.toml sha256 block
"""
import argparse
import hashlib
import os
import random
import struct
import sys

SEED = 20261018
REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BASE_REL = "101AA00DS0003.000"
CELL = "101AA00DS0003"
FT = 0x1E  # field terminator
UT = 0x1F  # unit terminator

MANIFEST_BEGIN = "# BEGIN update fixtures (generated by tools/gen_update_fixtures.py; do not edit)"
MANIFEST_END = "# END update fixtures"


# ---------------------------------------------------------------- ISO 8211 read / write

def read_records(b):
    """[(leader_bytes, [(tag, data_with_terminator)])] for a well-formed ISO 8211 file."""
    out = []
    off = 0
    while off < len(b):
        lead = b[off:off + 24]
        rec_len = int(lead[0:5])
        base = int(lead[12:17])
        ls, ps, ts = lead[20] - 48, lead[21] - 48, lead[23] - 48
        d = b[off + 24:off + base - 1]
        fields = []
        i = 0
        while i < len(d):
            tag = d[i:i + ts].decode("ascii")
            i += ts
            flen = int(d[i:i + ls]); i += ls
            fpos = int(d[i:i + ps]); i += ps
            fields.append((tag, b[off + base + fpos:off + base + fpos + flen]))
        out.append((lead, fields))
        off += rec_len
    if off != len(b):
        raise SystemExit("base cell does not end on a record boundary")
    return out


def build_data_record(fields):
    """Encode one 'D' record; field data must already end with FT."""
    area = b"".join(d for _, d in fields)
    max_len = max(len(d) for _, d in fields)
    max_pos = sum(len(d) for _, d in fields[:-1])
    ls = max(1, len(str(max_len)))
    ps = max(1, len(str(max_pos)))
    directory = bytearray()
    pos = 0
    for tag, d in fields:
        assert len(tag) == 4 and d.endswith(bytes([FT]))
        directory += tag.encode("ascii") + b"%0*d" % (ls, len(d)) + b"%0*d" % (ps, pos)
        pos += len(d)
    directory.append(FT)
    base = 24 + len(directory)
    rec_len = base + len(area)
    assert rec_len <= 99999
    leader = b"%05d D     %05d   %d%d0%d" % (rec_len, base, ls, ps, 4)
    assert len(leader) == 24
    return leader + bytes(directory) + area


def field(data):
    return bytes(data) + bytes([FT])


# ---------------------------------------------------------------- S-101 field helpers

def u16(v):
    return struct.pack("<H", v)


def u32(v):
    return struct.pack("<I", v)


def make_dsid(base_dsid, dsnm, ed, upd):
    """Rewrite DSNM and DSED ("ED.UPD", repo convention) of a base DSID field."""
    d = base_dsid[:-1]  # drop FT
    head, rest = d[:5], d[5:]
    parts = []
    for _ in range(7):  # ENSP ENED PRSP PRED PROF DSNM DSTL
        j = rest.index(bytes([UT]))
        parts.append(rest[:j])
        rest = rest[j + 1:]
    dsrd, rest = rest[:8], rest[8:]
    tail_parts = []
    for _ in range(3):  # DSLG DSAB DSED
        j = rest.index(bytes([UT]))
        tail_parts.append(rest[:j])
        rest = rest[j + 1:]
    parts[5] = dsnm.encode("ascii")
    tail_parts[2] = ("%d.%d" % (ed, upd)).encode("ascii")
    out = bytearray(head)
    for p in parts:
        out += p + bytes([UT])
    out += dsrd
    for p in tail_parts:
        out += p + bytes([UT])
    out += rest
    return field(out)


def frid(rcid, nftc, rver, ruin):
    return field(bytes([100]) + u32(rcid) + u16(nftc) + u16(rver) + bytes([ruin]))


def foid(agen, fidn, fids):
    return field(u16(agen) + u32(fidn) + u16(fids))


def attr(entries):
    out = bytearray()
    for natc, atix, paix, atin, value in entries:
        out += u16(natc) + u16(atix) + u16(paix) + bytes([atin]) + value.encode("ascii") + bytes([UT])
    return field(out)


def parse_codes(fdata):
    d = fdata[:-1]
    m = {}
    i = 0
    while bytes([UT]) in d[i:]:
        j = d.index(bytes([UT]), i)
        name = d[i:j].decode("ascii")
        m[name] = struct.unpack("<H", d[j + 1:j + 3])[0]
        i = j + 3
    return m


def first_attr(fdata):
    d = fdata[:-1]
    natc, atix, paix = struct.unpack("<HHH", d[:6])
    j = d.index(bytes([UT]), 7)
    return natc, atix, paix, d[7:j].decode("ascii")


# ---------------------------------------------------------------- fixture set

class Base:
    def __init__(self, raw):
        self.raw = raw
        recs = read_records(raw)
        self.ddr = raw[:int(recs[0][0][0:5])]
        assert chr(recs[0][0][6]) == "L"
        self.dsid_fields = dict(recs[1][1])
        assert "DSID" in self.dsid_fields
        self.dsid_rec_fields = recs[1][1]
        self.ftcs = parse_codes(self.dsid_fields["FTCS"])
        self.atcs = parse_codes(self.dsid_fields["ATCS"])
        self.features = []  # (rcid, nftc, fields-dict)
        for _, fields in recs[2:]:
            fd = dict(fields)
            if "FRID" in fd:
                f = fd["FRID"]
                self.features.append((struct.unpack("<I", f[1:5])[0],
                                      struct.unpack("<H", f[5:7])[0], fd))
        self.rcids = {r for r, _, _ in self.features}
        self.max_fidn = max(struct.unpack("<I", fd["FOID"][2:6])[0]
                            for _, _, fd in self.features if "FOID" in fd)


def generate(out_dir):
    rng = random.Random(SEED)
    raw = open(os.path.join(REPO, "testdata", "s101", BASE_REL), "rb").read()
    base = Base(raw)

    def dsid_record(ed, upd):
        fields = []
        for tag, d in base.dsid_rec_fields:
            if tag == "DSID":
                d = make_dsid(d, "%s.%03d" % (CELL, upd), ed, upd)
            fields.append((tag, d))
        return build_data_record(fields)

    def update(ed, upd, feature_records):
        return base.ddr + dsid_record(ed, upd) + b"".join(build_data_record(r) for r in feature_records)

    contour = base.ftcs["DepthContour"]
    natc_vdc = base.atcs["valueOfDepthContour"]
    contours = sorted(r for r, n, _ in base.features if n == contour)
    assert len(contours) >= 4, "need DepthContour features in base"
    template_rcid = contours[0]
    template = next(fd for r, _, fd in base.features if r == template_rcid)
    t_natc, t_atix, t_paix, t_value = first_attr(template["ATTR"])
    assert t_natc == natc_vdc
    agen = struct.unpack("<H", template["FOID"][0:2])[0]

    new_rcid = max(base.rcids) + 1
    new_fidn = base.max_fidn + 1
    # Seeded choice of the original feature deleted by .003 (any DepthContour but the template).
    delete_rcid = rng.choice(contours[1:])
    patched_value = "12"
    assert patched_value != t_value

    def insert_record(rcid, fidn, ruin=1):
        return [("FRID", frid(rcid, contour, 1, ruin)), ("FOID", foid(agen, fidn, 1)),
                ("ATTR", template["ATTR"]), ("SPAS", template["SPAS"])]

    def modify_attr_record(rcid, value, nftc=contour):
        return [("FRID", frid(rcid, nftc, 2, 3)),
                ("ATTR", attr([(natc_vdc, t_atix, t_paix, 3, value)]))]

    def delete_record(rcid, nftc=contour):
        return [("FRID", frid(rcid, nftc, 2, 2))]

    files = {}
    seq1 = update(9, 1, [insert_record(new_rcid, new_fidn)])
    files["seq/%s.001" % CELL] = seq1
    files["seq/%s.002" % CELL] = update(9, 2, [modify_attr_record(new_rcid, patched_value)])
    files["seq/%s.003" % CELL] = update(9, 3, [delete_record(delete_rcid)])
    files["bad_ed/%s.001" % CELL] = update(8, 1, [insert_record(new_rcid, new_fidn)])
    files["notupd/%s.000" % CELL] = raw

    # Truncated: valid .001 cut in half; the cut must land inside a record so its leader
    # claims more bytes than are on disk.
    half = len(seq1) // 2
    off = 0
    while off < half:
        off += int(seq1[off:off + 5])
    assert off != half, "cut fell on a record boundary"
    files["corrupt/trunc.001"] = seq1[:half]

    # Leader garbled: DDR leader replaced by seeded non-digit bytes.
    garbage = bytes(rng.choice(b"ABCDEFGHIJKLMNOPQRSTUVWXYZ!#$%&*+-/") for _ in range(24))
    files["corrupt/leader.001"] = garbage + seq1[24:]

    files["corrupt/ruin9.001"] = update(9, 1, [insert_record(new_rcid, new_fidn, ruin=9)])

    missing_rcid = 900000 + rng.randrange(1000)
    assert missing_rcid not in base.rcids
    files["corrupt/missing.001"] = update(9, 1, [delete_record(missing_rcid)])

    # 3 valid RUIN ops (insert, modify, delete) then Delete of a non-existent FRID.
    late_modify = contours[1] if contours[1] != delete_rcid else contours[2]
    late_delete = next(r for r in contours[1:] if r not in (late_modify,))
    files["corrupt/late_fail.001"] = update(9, 1, [
        insert_record(new_rcid, new_fidn),
        modify_attr_record(late_modify, "99"),
        delete_record(late_delete),
        delete_record(missing_rcid),
    ])

    files["catalog/CATALOG.XML"] = catalog_xml()

    # Session oracle 11 (rev 1.3): exchange set base + seq/.001 (valid) + a .002 whose DSID is
    # in sequence (9.2) but deletes a non-existent FRID -> MissingTarget at the 2nd update.
    files["session/%s.002" % CELL] = update(9, 2, [delete_record(missing_rcid)])
    files["session/CATALOG.XML"] = session_catalog_xml()

    meta = {
        "new_rcid": new_rcid, "patched_value": patched_value, "delete_rcid": delete_rcid,
        "missing_rcid": missing_rcid, "late_modify": late_modify, "late_delete": late_delete,
    }
    for rel in sorted(files):
        path = os.path.join(out_dir, *rel.split("/"))
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "wb") as fh:
            fh.write(files[rel])
    return files, meta


def catalog_xml():
    def meta(file_name, ed, upd, purpose):
        return (
            "    <S100XC:S100_DatasetDiscoveryMetadata>\n"
            "      <S100XC:fileName>%s</S100XC:fileName>\n"
            "      <S100XC:purpose>%s</S100XC:purpose>\n"
            "      <S100XC:editionNumber>%d</S100XC:editionNumber>\n"
            "      <S100XC:updateNumber>%d</S100XC:updateNumber>\n"
            "      <S100XC:productSpecification>\n"
            "        <S100XC:productIdentifier>S-101</S100XC:productIdentifier>\n"
            "        <S100XC:version>2.0.0</S100XC:version>\n"
            "      </S100XC:productSpecification>\n"
            "    </S100XC:S100_DatasetDiscoveryMetadata>\n" % (file_name, purpose, ed, upd))
    xml = (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<S100XC:S100_ExchangeCatalogue xmlns:S100XC="http://www.iho.int/s100/xc/5.2">\n'
        "  <S100XC:identifier>\n"
        "    <S100XC:identifier>update-robustness CatalogueMismatch fixture</S100XC:identifier>\n"
        "    <S100XC:dateTime>2026-10-18T00:00:00</S100XC:dateTime>\n"
        "  </S100XC:identifier>\n"
        "  <S100XC:datasetDiscoveryMetadata>\n"
        + meta("file:/../../%s" % BASE_REL, 9, 0, "newDataset")
        # DSID of seq/.001 says 9.1; the catalogue claims UPD 2 -> CatalogueMismatch.
        + meta("file:/../seq/%s.001" % CELL, 9, 2, "update")
        + "  </S100XC:datasetDiscoveryMetadata>\n"
        "</S100XC:S100_ExchangeCatalogue>\n")
    return xml.encode("ascii")


def session_catalog_xml():
    return _catalog([("file:/../../%s" % BASE_REL, 9, 0, "newDataset"),
                     ("file:/../seq/%s.001" % CELL, 9, 1, "update"),
                     ("file:/%s.002" % CELL, 9, 2, "update")],
                    "update-robustness session last-good-state fixture")


def _catalog(rows, ident):
    body = "".join(_meta(*r) for r in rows)
    return (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<S100XC:S100_ExchangeCatalogue xmlns:S100XC="http://www.iho.int/s100/xc/5.2">\n'
        "  <S100XC:identifier>\n"
        "    <S100XC:identifier>%s</S100XC:identifier>\n"
        "    <S100XC:dateTime>2026-10-18T00:00:00</S100XC:dateTime>\n"
        "  </S100XC:identifier>\n"
        "  <S100XC:datasetDiscoveryMetadata>\n" % ident
        + body
        + "  </S100XC:datasetDiscoveryMetadata>\n"
        "</S100XC:S100_ExchangeCatalogue>\n").encode("ascii")


