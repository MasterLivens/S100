def manifest_block(files):
    lines = [MANIFEST_BEGIN,
             "# Update-robustness fixtures (docs/update-robustness-contract.md rev 1.2).",
             "# Paths are relative to testdata/s101/. Base: %s." % BASE_REL,
             "[update_fixtures]",
             'generator = "tools/gen_update_fixtures.py"',
             "seed = %d" % SEED, ""]
    for rel in sorted(files):
        lines += ["[[update_fixture]]",
                  'path = "updates/%s"' % rel,
                  'sha256 = "%s"' % hashlib.sha256(files[rel]).hexdigest(), ""]
    lines.append(MANIFEST_END)
    return "\n".join(lines) + "\n"


def write_manifest(files):
    path = os.path.join(REPO, "testdata", "s101", "fixtures.toml")
    text = open(path, "rb").read().decode("utf-8").replace("\r\n", "\n")
    block = manifest_block(files)
    if MANIFEST_BEGIN in text:
        a = text.index(MANIFEST_BEGIN)
        b = text.index(MANIFEST_END) + len(MANIFEST_END) + 1
        text = text[:a] + block + text[b:]
    else:
        text = text.rstrip("\n") + "\n\n" + block
    with open(path, "wb") as fh:
        fh.write(text.encode("utf-8"))


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out", default=os.path.join(REPO, "testdata", "s101", "updates"))
    ap.add_argument("--write-manifest", action="store_true",
                    help="refresh the sha256 block in testdata/s101/fixtures.toml")
    args = ap.parse_args()
    files, meta = generate(args.out)
    for rel in sorted(files):
        print("%s  %s" % (hashlib.sha256(files[rel]).hexdigest(), rel))
    print("meta " + " ".join("%s=%s" % (k, meta[k]) for k in sorted(meta)))
    if args.write_manifest:
        write_manifest(files)
    return 0


if __name__ == "__main__":
    sys.exit(main())
